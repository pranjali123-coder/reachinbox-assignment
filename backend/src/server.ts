import express from 'express';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import { env } from './config/env.js';
import { connectRedis } from './lib/redis.js';
import { authRouter } from './routes/auth.js';
import { slackRouter } from './routes/slack.js';
import { emailsRouter } from './routes/emails.js';
import { meRouter } from './routes/me.js';
import { createBullBoard } from '@bull-board/api';
import { BullMQAdapter } from '@bull-board/api/bullMQAdapter.js';
import { ExpressAdapter } from '@bull-board/express';
import { emailQueue } from './queue/queue.js';

const app = express();
app.use(cors({ origin: env.FRONTEND_URL, credentials: true }));
app.use(express.json({ limit: '2mb' }));
app.use(cookieParser());
app.get('/api/health', (_, res) => res.json({ ok: true }));
app.use('/api/auth', authRouter);
app.use('/api/slack', slackRouter);
app.use('/api/me', meRouter);
app.use('/api/emails', emailsRouter);
const serverAdapter = new ExpressAdapter();
serverAdapter.setBasePath('/admin/queues');
createBullBoard({ queues: [new BullMQAdapter(emailQueue)], serverAdapter });
app.use('/admin/queues', serverAdapter.getRouter());
app.use((err: any, _req: express.Request, res: express.Response, _next: express.NextFunction) => { console.error(err); res.status(err?.name === 'ZodError' ? 400 : 500).json({ message: err?.message ?? 'Internal server error' }); });
connectRedis().then(() => app.listen(env.PORT, () => console.log(`API on http://localhost:${env.PORT}`))).catch(err => { console.error(err); process.exit(1); });
